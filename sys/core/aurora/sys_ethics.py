MANIFEST = "sys/core/ethics/MANIFEST.json"
FORBIDDEN = {"offensive_scan", "exploit", "denial_of_service", "person_lookup", "person_tracking",
             "credential_attack", "malware", "unauthorized_access", "impersonation"}
EXEMPT_PURPOSE = "aurora-ethics-level-B-exempt"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _canonical(files: dict) -> bytes:
    return json.dumps(files, sort_keys=True, separators=(",", ":")).encode()


def owner_public_key(path: Path | None = None) -> tuple[str, str]:
    """(public key hex, problem). Trusted only if root owns the file and its folder and nobody else
    can write them: a key Aurora could replace would protect nothing."""
    p = path or PUBLIC_KEY
    try:
        for x in (p.parent, p):
            st = x.stat()                                  # follows links: a link to a user's file fails here
            if st.st_uid != 0 or st.st_mode & 0o022:
                return "", f"{x} must belong to root and be writable by root only"
        text = p.read_text().strip()
        if len(bytes.fromhex(text)) != 32:
            raise ValueError
    except OSError:
        return "", f"no owner key at {p} (run: sudo /usr/bin/python3 -I sys/core/script/sys_root.py setup)"
    except ValueError:
        return "", f"{p} is not an Ed25519 public key"
    return text, ""


def _verify(message: bytes, signature_hex: str, public_hex: str) -> bool:
    from cryptography.exceptions import InvalidSignature
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
    try:
        key = Ed25519PublicKey.from_public_bytes(bytes.fromhex(public_hex))
        key.verify(bytes.fromhex(signature_hex), message)
        return True
    except (InvalidSignature, ValueError):
        return False


def integrity(root: Path = CODE_ROOT, public_hex: str = "") -> tuple[bool, str]:
    """(intact, reason): every protected file matches the signed manifest."""
    if not public_hex:
        public_hex, problem = owner_public_key()
        if not public_hex:
            return False, problem
    mf = root / MANIFEST
    if not mf.exists():
        return False, f"{MANIFEST} missing (run sys_ethics_sign.py sign)"
    try:
        m = json.loads(mf.read_text(encoding="utf-8"))
    except ValueError:
        return False, f"{MANIFEST} unreadable"
    if not _verify(_canonical(m.get("files", {})), m.get("signature", ""), public_hex):
        return False, "the manifest signature is not the owner's"
    if set(m["files"]) != set(PROTECTED):
        return False, "the manifest does not cover the protected files"
    changed = [f for f, h in m["files"].items() if not (root / f).exists() or _sha(root / f) != h]
    return (False, f"changed without the owner's signature: {', '.join(changed)}") if changed else (True, "intact")


CODE_PATTERNS = ("install.sh", "uninstall.sh", "requirements.txt",
                 "requirements.lock", "pyproject.toml",         # C558: what the installer resolves and pins
                 "sys/core/**/*.py", "sys/core/**/*.js",
                 "sys/core/**/*.mjs",                           # C558: modules served to browsers and the JS tests
                 "sys/core/**/*.css", "sys/core/**/*.html", "sys/core/**/*.json", "sys/core/**/*.md", "sys/core/**/*.sh",
                 "sys/core/config/*",                           # C558: allowed_signers (the updater's trust) has no suffix
                 "sys/plugins/**/*",                            # C558: a plugin's sub-folders too (unsigned_plugins: the same)
                 ".github/**/*",                                # C558: what CI runs on the published code
                 "sys/deploy/**/*")   # what root installs: aurora-root runs only these files as signed (sys_root, 9 Nov)
DATA_FILES = ("sys/core/config/shadow_seed.json",)  # rewritten every day by its timer (C401): data, not code
# Folders the services write, never the owner (C558): Python's caches, and what plg_deps fetches into a plugin on the
# owner's «install» (pip --target, dpkg-deb -x — every file checked against the hashes its plugin.json pins, and that
# manifest IS signed) and removes on «uninstall». Signing them would make every install a drift, and ngspice's tree
# carries symbolic links, which root's launcher refuses (sys_root.snapshot). Outside the signature, by folder name.
RUNTIME_DIRS = ("__pycache__", ".deps", ".bin", ".deps.tmp", ".bin.tmp")


def _forged_prefixes(root: Path) -> set[str]:
    return {f"sys/plugins/{n}/" for n in forged_plugins(root)}


def _is_code(rel: str, forged: set[str]) -> bool:
    """One rule for code_files and unsigned_plugins (C558): with two, a plugin's file could be signed and never checked,
    or checked and never signed."""
    return (not any(part in RUNTIME_DIRS for part in rel.split("/"))
            and rel not in (MANIFEST, "sys/core/ethics/exemption.sig") and rel not in DATA_FILES
            and not any(rel.startswith(f) for f in forged))


def _plugin_files(folder: Path) -> Iterator[Path]:
    """Every file of one plugin, sub-folders included, the runtime folders pruned before they are entered (C558: .deps
    and .bin hold thousands of files; walking them to discard them would cost every start). Links to folders are not
    followed; a link to a file is yielded like a file, so that root's launcher sees and refuses it (sys_root.snapshot)."""
    for dirpath, dirnames, filenames in os.walk(folder):
        dirnames[:] = [d for d in dirnames if d not in RUNTIME_DIRS]
        for name in filenames:
            yield Path(dirpath) / name


def forged_plugins(root: Path = CODE_ROOT) -> set[str]:
    """The plugins Aurora wrote herself (their manifest says "forged"): under their contract, not the owner's signature
    — the cage holds them to it at every start (plg_sandbox: the projects' folder at most, their own settings, the
    network only through plg_netproxy), so she makes and uses them without a signature each time (owner, 9 Nov)."""
    out = set()
    for mf in (root / "sys" / "plugins").glob("*/plugin.json"):
        try:
            if json.loads(mf.read_text(encoding="utf-8")).get("forged"):
                out.add(mf.parent.name)
        except (OSError, ValueError):
            continue
    return out


def code_files(root: Path = CODE_ROOT) -> list[str]:
    """Every file of the code base the owner signs as a whole (the second tier: changes are reported, not fatal); the
    plugins Aurora wrote herself are not among them (forged_plugins: their contract holds them)."""
    found, forged = set(), _forged_prefixes(root)
    for pattern in CODE_PATTERNS:
        if pattern == "sys/plugins/**/*":                 # C558: walked with the runtime folders pruned, not globbed through
            for d in sorted((root / "sys" / "plugins").iterdir()) if (root / "sys" / "plugins").is_dir() else []:
                if d.is_dir():
                    found.update(p.relative_to(root).as_posix() for p in _plugin_files(d) if p.is_file())
            continue
        found.update(p.relative_to(root).as_posix() for p in root.glob(pattern) if p.is_file())
    return sorted(rel for rel in found if _is_code(rel, forged))


_unsigned_cache: dict = {}


def unsigned_plugins(root: Path = CODE_ROOT, public_hex: str = "") -> set[str]:
    """The owner's plugins (not forged) whose files are not as he signed them: not loaded (9 Nov — a plugin is either
    the owner's and signed, or Aurora's under its contract; never a third kind). Without a signed code list at all (a
    port, an installation before the code was signed) nothing is held back: the integrity check speaks for it."""
    import time
    mf = root / MANIFEST
    plugins = root / "sys" / "plugins"
    try:                                                   # C558: the sub-folders' files count in the stamp too
        stamp = (mf.stat().st_mtime, max((p.stat().st_mtime for d in plugins.iterdir() if d.is_dir()
                                          for p in _plugin_files(d)), default=0))
    except OSError:
        return set()
    hit = _unsigned_cache.get(str(root))
    if hit and hit[0] == stamp and time.time() - hit[1] < 30:
        return hit[2]
    out: set[str] = set()
    if not public_hex:
        public_hex, _ = owner_public_key()
    try:
        m = json.loads(mf.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        m = {}
    code = m.get("code") or {}
    if public_hex and code and _verify(_canonical(code), m.get("code_signature", ""), public_hex):
        forged = forged_plugins(root)
        for d in plugins.iterdir() if plugins.is_dir() else []:
            if not d.is_dir() or d.name in forged or not (d / "plugin.json").exists():
                continue
            for f in _plugin_files(d):                     # C558: the sub-folders too, with code_files' own exclusions
                rel = f.relative_to(root).as_posix()
                if f.is_file() and _is_code(rel, set()) and code.get(rel) != _sha(f):
                    out.add(d.name)
                    break
    _unsigned_cache[str(root)] = (stamp, time.time(), out)
    return out


def code_drift(root: Path = CODE_ROOT, public_hex: str = "") -> dict:
    """{"changed", "added", "removed"} files against the signed code list; {"unsigned": reason} if there is none.
    The rules (PROTECTED) stop Aurora when changed; the rest of the code is made evident, so that a self-repair
    the owner approved does not stop her until he signs again."""
    if not public_hex:
        public_hex, problem = owner_public_key()
        if not public_hex:
            return {"unsigned": problem}
    try:
        m = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"unsigned": f"{MANIFEST} missing or unreadable"}
    code = m.get("code")
    if not code:
        return {"unsigned": "the manifest has no code list (sign again)"}
    if not _verify(_canonical(code), m.get("code_signature", ""), public_hex):
        return {"unsigned": "the code list is not signed by the owner"}
    code = {k: v for k, v in code.items() if k not in DATA_FILES}   # signed before C401: not code any more
    now = set(code_files(root))
    return {"changed": sorted(f for f in now & set(code) if _sha(root / f) != code[f]),
            "added": sorted(now - set(code)), "removed": sorted(set(code) - now)}


def drift_summary(d: dict) -> str:
    if "unsigned" in d:
        return d["unsigned"]
    n = len(d["changed"]) + len(d["added"]) + len(d["removed"])
    return "" if not n else (f"{n} code files differ from the owner's signature: "
                             + ", ".join((d["changed"] + d["added"] + d["removed"])[:8]) + (" …" if n > 8 else ""))


def require_intact(log=None) -> None:
    """Every service calls this at start: rules changed without the owner mean no Aurora."""
    ok, reason = integrity()
    if not ok:
        msg = f"ethics code check failed: {reason}. Aurora does not start."
        if log:
            log.critical(msg)
        print(msg, file=sys.stderr)
        sys.exit(78)                                       # EX_CONFIG: systemd does not loop on it
    if log:
        log.info("ethics code: intact; level B %s", "exempted (owner)" if exempt() else "active")
        drift = drift_summary(code_drift())
        if drift:
            log.warning("code signature: %s", drift)


def machine_id() -> str:
    try:
        return Path("/etc/machine-id").read_text().strip()
    except OSError:
        return "unknown-machine"


def exemption_message(root: Path) -> bytes:
    return f"{EXEMPT_PURPOSE}|{machine_id()}|{root}".encode()


@lru_cache(maxsize=8)
def _exempt_cached(path: str, mtime: float, root: str, public_hex: str) -> bool:
    try:
        sig = Path(path).read_text().strip()
    except OSError:
        return False
    return _verify(exemption_message(Path(root)), sig, public_hex)


def exempt(cfg: sys_config.Config | None = None) -> bool:
    """Is this installation exempted from level B by the owner?"""
    cfg = cfg or sys_config.get()
    p = cfg.path("AURORA_ETHICS_EXEMPTION")
    public_hex, _ = owner_public_key()
    if not p.exists() or not public_hex:
        return False
    return _exempt_cached(str(p), p.stat().st_mtime, str(cfg.root), public_hex)


def forbidden_capabilities(manifest: dict) -> list[str]:
    """Level A: capabilities a plugin may never have."""
    return sorted(set(manifest.get("capabilities", [])) & FORBIDDEN)
