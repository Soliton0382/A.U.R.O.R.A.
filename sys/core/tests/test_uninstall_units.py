"""C574: uninstall.sh takes the units to remove from root's own folder — the services naming this installation, their
generated timer, path and target — never from sys/deploy/systemd (a folder the services' account writes)."""
from __future__ import annotations

import re
import subprocess
from pathlib import Path

UNINSTALL = Path(__file__).resolve().parents[3] / "uninstall.sh"
GEN = "# Generated from .env by sys/core/script/sys_install_services.py\n"


def _units(etc: Path, root: Path) -> set[str]:
    text = UNINSTALL.read_text(encoding="utf-8")
    start = text.index('UNITS=""')
    ends = [m.end() for m in re.finditer(r"^done$", text[start:], re.M)]
    block = text[start:start + ends[2]].replace("/etc/systemd/system", str(etc))
    out = subprocess.run(["bash", "-c", f'ROOT="{root}"\n{block}\necho $UNITS'], capture_output=True, text=True,
                         check=True).stdout
    return set(out.split())


def test_only_this_installation_s_units_are_removed(tmp_path):
    etc, root = tmp_path / "etc", tmp_path / "my aurora"
    etc.mkdir()
    (etc / "aurora-api.service").write_text(f"{GEN}[Service]\nWorkingDirectory={root}\n")
    (etc / "aurora-api.service.d").mkdir()
    (etc / "aurora-backup.service").write_text(f"{GEN}ExecStart={root}/.venv/bin/python x\n")
    (etc / "aurora-backup.timer").write_text(f"{GEN}[Timer]\n")
    (etc / "aurora.target").write_text(f"{GEN}[Unit]\n")
    (etc / "aurora-certs.path").write_text("# Generated by sys/core/script/sys_install_services.py\n[Path]\n")
    (etc / "aurora-other.service").write_text(f"{GEN}WorkingDirectory=/elsewhere/aurora\n")   # another installation
    (etc / "aurora-old.timer").write_text("[Timer]\n")                                          # not generated
    (etc / "aurora-x.service").symlink_to(etc / "aurora-api.service")                          # a link: never
    assert _units(etc, root) == {"aurora-api.service", "aurora-api.service.d", "aurora-backup.service",
                                 "aurora-backup.timer", "aurora.target"}


def test_nothing_of_another_installation_is_taken(tmp_path):
    etc = tmp_path / "etc"
    etc.mkdir()
    (etc / "aurora.target").write_text(f"{GEN}[Unit]\n")
    (etc / "aurora-api.service").write_text(f"{GEN}WorkingDirectory=/elsewhere\n")
    assert _units(etc, tmp_path / "mine") == set()
