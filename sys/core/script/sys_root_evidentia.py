def backup_key(prefix: Path) -> str | None:
    """Evidentia's backup key, made once (32 random bytes, root 0600); its recovery code returned that once only — to
    keep outside this machine. Never removed (old backups need it)."""
    k = prefix / BACKUP_KEY
    if k.exists():
        return None
    k.parent.mkdir(parents=True, exist_ok=True)
    raw = os.urandom(32)
    fd = os.open(k, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(raw)
    import base64
    code = base64.b32encode(raw).decode().rstrip("=")
    return "-".join(code[i:i + 4] for i in range(0, len(code), 4))


def unit_path(p: Path | str, exec_arg: bool = False) -> str:
    """A path written in a unit so that systemd reads it back as is (a space, a %, a $ — Evidentia's B34)."""
    s = str(p).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    if exec_arg:
        s = s.replace("$", "$$")
    return f'"{s}"'


