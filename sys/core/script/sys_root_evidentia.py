"""`aurora-root install evidentia` / `uninstall evidentia`: Evidentia, the document investigator, as an add-on of
Aurora (owner, 27 Nov: «evidentia pubblica dentro aurora… come concetto un plugin nella sua sandbox… non voglio che
aurora si sporchi con quei file»).

Run by root's copy of sys_root.py after the signature and root's copy (sync_lib carries sys/evidentia/). It makes:
  the account «evidentia» and the groups «evidentia» (the archive: the owner in it, aurora NOT) and «evidentia-api»
  (the socket: aurora in it — she asks, she never reads the files);
  /usr/local/lib/aurora-evidentia/venv     Python for the service, root's, read only for it: built OFFLINE from the
                                           wheelhouse (sys/runtime/evidentia-wheels) with every wheel's SHA-256 pinned
                                           by sys/evidentia/config/requirements-root.lock (a changed wheel stops it);
  /etc/aurora/evidentia.env                its settings (root 0640, group evidentia): the archive's folders;
  usr/<owner>/evidentia                    the owner's archive folder (evidentia:evidentia 2770): Aurora cannot read it;
  /etc/systemd/system/evidentia-api.service  the API on a unix socket (/var/lib/evidentia-api), no network, the code from
                                           root's copy (/usr/local/lib/aurora/sys/evidentia), the same confinement as
                                           before (ProtectSystem=strict, ProtectHome=tmpfs + binds, PrivateNetwork…).
An existing installation (the separate folder of 10 Nov) is taken over: its archive, models and sources folders are
read from its .env and kept where they are, until the owner moves them (the folder is the setting). Uninstall stops
and removes the unit, the settings and the venv; the archive and the account are never removed (the data are the
owner's). Every path sits under `prefix` (default /) so a test can install in a folder of its own."""
