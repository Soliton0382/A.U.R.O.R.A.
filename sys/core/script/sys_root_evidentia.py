def backup_settings(cfg=None) -> dict:
    """Where and when, from Aurora's backup settings: the same destination (its «evidentia» folder), the same
    retention, half an hour after Aurora's own run. Without Aurora's settings: no backup (said at install)."""
    try:
        if cfg is None:
            from aurora import sys_config
            cfg = sys_config.get()
        raw = str(cfg["AURORA_BACKUP_DIR"] or "").strip()
        if not raw:
            return {}
        if raw.startswith("smb://"):
            from aurora.sys_backup import NAS_MOUNT
            sub = "/".join(raw[6:].strip("/").split("/")[2:])
            base = NAS_MOUNT / sub if sub else NAS_MOUNT
        else:
            base = Path(os.path.expanduser(raw))
        hh, mm = (int(x) for x in str(cfg["AURORA_BACKUP_TIME"]).split(":"))
        t = (hh * 60 + mm + 30) % (24 * 60)
        return {"EVD_BACKUP_DIR": str(base / "evidentia"), "EVD_BACKUP_KEY_FILE": "/" + BACKUP_KEY,
                "EVD_BACKUP_KEEP_DAILY": str(cfg["AURORA_BACKUP_KEEP_DAILY"]),
                "EVD_BACKUP_KEEP_WEEKLY": str(cfg["AURORA_BACKUP_KEEP_WEEKLY"]),
                "EVD_BACKUP_KEEP_MONTHLY": str(cfg["AURORA_BACKUP_KEEP_MONTHLY"]), "time": f"{t // 60:02d}:{t % 60:02d}"}
    except Exception:                                   # noqa: BLE001 — no settings: the install says it, goes on
        return {}


