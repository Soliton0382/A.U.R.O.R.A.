def env_text(folders: dict[str, Path], backup: dict | None = None, nas: str = "", owner: str = "") -> str:
    import sys_root_evidentia_nas as N
    return "".join(f"{k}={'' if str(folders[k]) in ('', '.') else folders[k]}\n" for k in KEYS) + \
        (f"EVD_OWNER={owner}\nEVD_ARCHIVE_DIR={ARCHIVE}\n" if owner else "") + \
        f"EVD_SOCKET_GROUP={API_GROUP}\n" + "".join(f"{k}={v}\n" for k, v in (backup or {}).items() if k != "time") + \
        (f"EVD_NAS_SOURCES={nas}\nEVD_NAS_DIR={N.MOUNT}\n" if nas else "")


def _parse_env(text: str) -> dict[str, str]:
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip().strip('"').strip("'")
    return out


def folders_for(repo: Path, owner: str, old_root: Path | None) -> dict[str, Path]:
    """The archive's folders: those of an existing installation (its .env, kept where they are), else the owner's
    folder in Aurora (usr/<owner>/evidentia, with data/, models/, sources/ in it)."""
    old = {}
    if old_root and (old_root / ".env").is_file():
        vals = _parse_env((old_root / ".env").read_text(encoding="utf-8"))
        defaults = {}                                   # what the earlier service used when its .env said nothing:
        try:                                            # its own schema's recommended values (27 Nov, measured)
            sch = json.loads((old_root / "sys" / "core" / "config" / "settings_schema.json").read_text(encoding="utf-8"))
            defaults = {x["key"]: x.get("recommended", "") for x in sch.get("settings", [])}
        except (OSError, ValueError, KeyError):
            pass
        for k in KEYS:
            v = vals.get(k) or defaults.get(k, "")
            if v:
                p = Path(v)
                old[k] = p if p.is_absolute() else old_root / p
        if not {"EVD_DATA_DIR", "EVD_MODELS_DIR"} <= set(old):   # review B1: never a guess for the archive itself
            raise SystemExit(f"evidentia: {old_root}: its archive or models folder is unknown: write them in its .env")
    base = ARCHIVE / owner                       # review A2: outside Aurora's tree (usr/ is aurora's), one per user
    if old:                                             # an earlier archive: its folders; no sources folder = none bound
        return {"EVD_DATA_DIR": old["EVD_DATA_DIR"], "EVD_MODELS_DIR": old["EVD_MODELS_DIR"],
                "EVD_SOURCES_DIR": old.get("EVD_SOURCES_DIR", Path(""))}
    return {"EVD_DATA_DIR": base / "data", "EVD_MODELS_DIR": base / "models", "EVD_SOURCES_DIR": base / "sources"}


def _put(write, prefix: Path, rel: str, text: str, mode: int, gid: int = 0) -> Path:
    p = prefix / rel
    for d in reversed([p.parent, *p.parent.parents]):
        if d == prefix or prefix not in [d, *d.parents]:
            continue
        if not d.exists():
            d.mkdir(mode=0o755)
    write(p, text.encode(), mode, (0, gid))
    return p


def venv(prefix: Path, repo: Path, run=subprocess.run, signed: Path | None = None) -> Path:
    """Root's venv, rebuilt only when the lock changed (its SHA-256 kept beside it); offline, hashes required.
    Review of 27 Nov (A1): the lock is read from ROOT'S SIGNED COPY (`signed`, /usr/local/lib/aurora), never from the
    repository aurora can write; the wheels are copied into a folder of root's first (no file swapped between pip's
    check and its install); binaries only, no dependency outside the lock."""
    import hashlib
    import shutil
    import tempfile
    v = prefix / VENV
    lock = (signed or Path(LIB)) / LOCK
    data = lock.read_bytes()
    want = hashlib.sha256(data).hexdigest()
    mark = v / ".lock.sha256"
    if mark.is_file() and mark.read_text().strip() == want:
        return v
    with tempfile.TemporaryDirectory(prefix="evidentia-wheels-") as tmp:
        t = Path(tmp)
        (t / "requirements.lock").write_bytes(data)
        wheels = t / "wheels"
        wheels.mkdir()
        for w in (repo / WHEELS).glob("*.whl"):
            if w.is_file() and not w.is_symlink():
                shutil.copyfile(w, wheels / w.name)
        run(["/usr/bin/python3", "-I", "-m", "venv", "--clear", str(v)], check=True)
        run([str(v / "bin" / "python"), "-I", "-m", "pip", "install", "--no-index", "--no-cache-dir", "--only-binary=:all:",
             "--no-deps", "--find-links", str(wheels), "--require-hashes", "-r", str(t / "requirements.lock")], check=True)
    mark.write_text(want + "\n")
    return v


def _exists(kind: str, name: str) -> bool:
    try:
        (pwd.getpwnam if kind == "user" else grp.getgrnam)(name)
        return True
    except KeyError:
        return False


def _member(user: str, group: str) -> bool:
    try:
        return user in grp.getgrnam(group).gr_mem or pwd.getpwnam(user).pw_gid == grp.getgrnam(group).gr_gid
    except KeyError:
        return False


def accounts(owner: str, run=subprocess.run) -> None:
    if not _exists("group", API_GROUP):
        run(["groupadd", "--system", API_GROUP], check=True)
    if not _exists("user", USER):
        run(["useradd", "--system", "--user-group", "--no-create-home", "--home-dir", "/nonexistent",
             "--shell", "/usr/sbin/nologin", USER], check=True)
    for user, group in ((USER, API_GROUP), (owner, GROUP), ("aurora", API_GROUP)):
        if _exists("user", user) and not _member(user, group):
            run(["usermod", "-aG", group, user], check=True)
    if _member("aurora", GROUP):                         # the separation: aurora asks through the socket, never reads
        run(["gpasswd", "-d", "aurora", GROUP], check=True)


def _mkdir_safe(path: Path, uid: int, gid: int, mode: int) -> None:
    """A folder made or checked without following a link: an existing one must be a real folder (not a link) and
    loses any ACL (setfacl -b) before it gets its owner and mode through its own descriptor."""
    try:
        os.mkdir(path, mode)
    except FileExistsError:
        pass
    fd = os.open(path, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
    try:
        os.fchown(fd, uid, gid)
        os.fchmod(fd, mode)
    finally:
        os.close(fd)
    subprocess.run(["setfacl", "-b", str(path)], check=False)


def archive_folder(folders: dict[str, Path], new: bool) -> None:
    """A new archive under /var/lib/evidentia (root-owned parent: nothing aurora can prepare or replace); an existing
    archive (an earlier install) is left as it is."""
    gid = grp.getgrnam(GROUP).gr_gid
    uid = pwd.getpwnam(USER).pw_uid
    # R15: the users' archives — root's, written by Evidentia's group only (the service makes <user>/data there; Aurora's
    # account is not in the group and can prepare nothing)
    _mkdir_safe(ARCHIVE, 0, gid, 0o2770)
    if not new:
        return
    owner_dir = folders["EVD_DATA_DIR"].parent
    if owner_dir.parent != ARCHIVE:
        raise SystemExit(f"evidentia: a new archive only under {ARCHIVE}")
    _mkdir_safe(owner_dir, uid, gid, 0o2770)
    for k in KEYS:
        _mkdir_safe(folders[k], uid, gid, 0o2770)


def previous_install(unit_file: Path = Path("/") / UNIT_PATH) -> Path | None:
    """The folder of an installation made before Evidentia moved into Aurora: the WorkingDirectory of the unit it
    wrote, when that is not root's copy and holds a .env (its archive's folders are taken from there)."""
    try:
        for line in unit_file.read_text(encoding="utf-8").splitlines():
            if line.startswith("WorkingDirectory="):
                d = Path(line.split("=", 1)[1].strip())
                return d if str(d) != LIB and (d / ".env").is_file() else None
    except OSError:
        return None
    return None


def install(write, repo: Path, owner: str, prefix: Path = Path("/"), run=subprocess.run,
            old_root: Path | None = None, backup_cfg=None, nas: str | None = None) -> dict:
    current = prefix / ENV                               # installed before: its folders, never a new empty archive
    if current.is_file():
        vals = _parse_env(current.read_text(encoding="utf-8"))
        folders = {k: Path(vals[k]) for k in KEYS if vals.get(k)}
        folders.setdefault("EVD_SOURCES_DIR", Path(""))  # the sources folder is optional (chosen from the WebUI)
        nas = nas if nas is not None else vals.get("EVD_NAS_SOURCES", "")
        if set(folders) != set(KEYS):                   # review B1: never fill the gaps with guesses
            raise SystemExit(f"evidentia: {ENV} lacks some of {', '.join(KEYS)}: write them, then install again")
        new = False
    else:
        folders = folders_for(repo, owner, old_root)
        new = not (old_root and (old_root / ".env").is_file())
    nas = (nas or "").strip()
    if nas:
        import sys_root_evidentia_nas as N
        N.parse(nas)                                    # checked before anything is written
    v = venv(prefix, repo, run, signed=None if prefix == Path("/") else repo)
    gid = grp.getgrnam(GROUP).gr_gid if prefix == Path("/") else 0
    b = backup_settings(backup_cfg) if backup_cfg is not False else {}
    code = backup_key(prefix) if b else None
    _put(write, prefix, ENV, env_text(folders, b, nas, owner), 0o640, gid)
    _put(write, prefix, UNIT_PATH, unit_text(Path("/") / VENV, folders), 0o644)
    if b:
        _put(write, prefix, f"etc/systemd/system/{BACKUP_UNIT}", backup_unit_text(Path("/") / VENV, folders, b), 0o644)
        _put(write, prefix, f"etc/systemd/system/{BACKUP_TIMER}", backup_timer_text(b["time"]), 0o644)
    if prefix == Path("/"):
        archive_folder(folders, new)
        _mkdir_safe(Path(RUN_DIR), pwd.getpwnam(USER).pw_uid, grp.getgrnam(API_GROUP).gr_gid, 0o2750)
        Path(BACKUP_STATE).mkdir(mode=0o700, exist_ok=True)
        mounted = None
        if nas:                                         # R22: its sources on the NAS, read only (sys_root_evidentia_nas)
            import sys_root_evidentia_nas as N
            mounted = N.mount(nas, pwd.getpwnam(USER).pw_uid, grp.getgrnam(GROUP).gr_gid, USER, run)
        run(["systemctl", "daemon-reload"], check=True)
        run(["systemctl", "enable", UNIT], check=True)
        run(["systemctl", "restart", UNIT], check=True)
        if b:
            run(["systemctl", "enable", "--now", BACKUP_TIMER], check=True)
    return {"venv": str(v), "folders": {k: str(p) for k, p in folders.items()}, "socket": SOCKET,
            "backup": {k: v for k, v in b.items() if k in ("EVD_BACKUP_DIR", "time")}, "recovery_code": code,
            "nas": (mounted if prefix == Path("/") and nas else {"set": bool(nas)})}


def uninstall(prefix: Path = Path("/"), run=subprocess.run) -> list[str]:
    """The unit, the settings and the venv; the archive and the account stay (they are the owner's)."""
    import shutil
    if prefix == Path("/"):
        run(["systemctl", "disable", "--now", UNIT], check=False)
    gone = []
    if prefix == Path("/"):
        run(["systemctl", "disable", "--now", BACKUP_TIMER], check=False)
    for rel in (UNIT_PATH, ENV, f"etc/systemd/system/{BACKUP_UNIT}", f"etc/systemd/system/{BACKUP_TIMER}"):
        p = prefix / rel
        if p.is_file() and not p.is_symlink():
            p.unlink()
            gone.append(str(p))
    v = prefix / VENV
    if v.is_dir() and not v.is_symlink():
        shutil.rmtree(v)
        gone.append(str(v))
    if prefix == Path("/"):
        import sys_root_evidentia_nas as N
        gone += N.unmount(run)                          # the NAS's line and credentials (its files untouched)
        run(["systemctl", "daemon-reload"], check=False)
    return gone


def main(action: str, write, repo: Path, yes: bool, extra: list[str] | None = None) -> int:
    extra = list(extra or [])
    nas = extra[extra.index("--nas") + 1] if "--nas" in extra and extra.index("--nas") + 1 < len(extra) else None
    owner = os.environ.get("SUDO_USER") or ""
    if action == "install":
        if not owner or owner == "root":
            print("evidentia: run it with sudo from the owner's account", file=sys.stderr)
            return 1
        accounts(owner)
        out = install(write, repo, owner, old_root=previous_install(), nas=nas)
        print(f"  Evidentia installata: ambiente {out['venv']}, socket {out['socket']}")
        if out["backup"]:
            print(f"  Backup di Evidentia: ogni giorno alle {out['backup']['time']}, in {out['backup']['EVD_BACKUP_DIR']}")
        else:
            print("  Backup di Evidentia: non attivo (imposta prima la destinazione dei backup di Aurora, poi reinstalla)")
        if out["recovery_code"]:
            print("  ⚠️  CODICE DI RECUPERO del backup di Evidentia (mostrato SOLO ORA; conservalo fuori da questa macchina,")
            print("      per esempio nel gestore di password: senza, i backup di Evidentia non si possono leggere):")
            print(f"      {out['recovery_code']}")
        for k, p in out["folders"].items():
            print(f"  {k} = {p}")
        n = out.get("nas") or {}
        if n.get("ok"):
            print(f"  📂 NAS delle fonti: {n['mount']} in sola lettura, {n['folders']} cartelle viste dall'utente evidentia")
        elif n.get("error"):
            print(f"  ⚠️  NAS delle fonti non montato: {n['error']}")
        print("  Aurora la raggiunge dal socket dopo il suo prossimo riavvio; i file restano dell'archivio, non suoi.")
        return 0
    if action == "uninstall":
        for p in uninstall():
            print(f"  tolto {p}")
        print("  L'archivio e l'account evidentia restano: i dati sono tuoi.")
        return 0
    print("evidentia: install or uninstall", file=sys.stderr)
    return 1
