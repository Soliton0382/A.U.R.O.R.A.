"""Evidentia made a system service (F0, owner 10 Nov: «rendiamo già ufficiale il server… se riavvio riparte da
solo»). Run once by the owner, with the system's Python and nothing else on its path:

    sudo /usr/bin/python3 -I sys/evidentia/script/evd_root.py install          # or --dry-run to see what it would do

It makes, and on a second run only checks again (every step idempotent):
- the account «evidentia»: a system one, no login, no home; its group «evidentia» holds the archive, shared
  with the owner (who runs the long jobs);
- the group «evidentia-api»: only the API's socket; its members are the service and Aurora's account, so Aurora
  reaches the socket and nothing else of the archive;
- the archive's folders (sys/data, sys/status, sys/logs) of group «evidentia», group-writable, closed to others
  (sys/status keeps the passage to the socket only);
- the unit evidentia-api.service: no network, the system read-only, only those three folders writable, no
  privilege, started at boot and again after a failure.
- the move from the first install, under the project's first name (10 Nov: «si chiami Evidentia ovunque»): the
  old unit stopped and removed, the old account and groups deleted, the old passage through the home taken away —
  only if they are still there.
Standard library only; the units run as «evidentia», never as root."""
from __future__ import annotations

import grp
import os
import pwd
import shlex
import stat
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
USER, GROUP, API_GROUP = "evidentia", "evidentia", "evidentia-api"
UNIT = "evidentia-api.service"
WRITABLE = ("sys/data", "sys/status", "sys/logs")
DRY = "--dry-run" in sys.argv
OLD_USER, OLD_API_GROUP, OLD_UNIT = "investigatore", "investigatore-api", "investigatore-api.service"   # the first name
OLD_MCP_UNIT = "investigatore-mcp.service"      # V8's MCP server (B32): run as the owner, port 8002 on every address
OLD_UNITS = (OLD_UNIT, OLD_MCP_UNIT)
SYSTEMD = Path("/etc/systemd/system")


def unit_path(p: Path | str, exec_arg: bool = False) -> str:
    """A path written in a unit so that systemd reads it back as is (B34: a space split it, a % was a specifier):
    in double quotes, backslash and quote escaped, % doubled; for an ExecStart argument $ doubled too (an environment
    variable otherwise). ExecStart, BindPaths and BindReadOnlyPaths all unquote their words this way."""
    s = str(p).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%")
    if exec_arg:
        s = s.replace("$", "$$")
    return f'"{s}"'


def unit_text(root: Path) -> str:
    """The unit evidentia-api.service for a project at root. WorkingDirectory takes its whole value as one path
    (spaces included, nothing to quote) but expands specifiers: only % is doubled there."""
    return f"""# Generated by sys/evidentia/script/evd_root.py — Evidentia's API on a unix socket
[Unit]
Description=Evidentia API (unix socket, no network)
After=local-fs.target

[Service]
Type=simple
User={USER}
Group={GROUP}
SupplementaryGroups={API_GROUP}
UMask=0007
WorkingDirectory={str(root).replace('%', '%%')}
ExecStart={unit_path(root / ".venv" / "bin" / "python", True)} {unit_path(root / "sys" / "evidentia" / "script" / "svc_api.py", True)}
Environment=EVD_SOCKET_GROUP={API_GROUP}
Restart=on-failure
RestartSec=5
MemoryMax=6G
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=tmpfs
BindReadOnlyPaths={unit_path(root)}
BindPaths={' '.join(unit_path(root / w) for w in WRITABLE)}
PrivateTmp=yes
PrivateDevices=yes
PrivateNetwork=yes
RestrictAddressFamilies=AF_UNIX
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
SystemCallArchitectures=native
SystemCallFilter=@system-service
SystemCallErrorNumber=EPERM
ProtectProc=invisible
ProcSubset=pid
CapabilityBoundingSet=
AmbientCapabilities=

[Install]
WantedBy=multi-user.target
"""


UNIT_TEXT = unit_text(ROOT)


def run(*cmd: str, check: bool = True) -> None:
    print("  $", " ".join(shlex.quote(c) for c in cmd))
    if not DRY:
        subprocess.run(cmd, check=check)


def exists(kind: str, name: str) -> bool:
    try:
        (pwd.getpwnam if kind == "user" else grp.getgrnam)(name)
        return True
    except KeyError:
        return False


def member(user: str, group: str) -> bool:
    return exists("group", group) and (user in grp.getgrnam(group).gr_mem or
                                       (exists("user", user) and pwd.getpwnam(user).pw_gid == grp.getgrnam(group).gr_gid))


def own(top: Path, gid: int) -> None:
    """The group and the modes of a tree, never through a symbolic link: a link is skipped, not followed (the folders
    are written by the service; root must not be led elsewhere by a link planted there). Every entry is reached
    from its folder's open descriptor (os.fwalk), never by its path: a folder swapped for a link between the listing
    and the descent is not followed (audit E7, B22: os.walk went by path, and was led out of the tree)."""
    for base, dirs, files, dfd in os.fwalk(top, follow_symlinks=False):
        for name in [*dirs, *files]:
            st = os.stat(name, dir_fd=dfd, follow_symlinks=False)
            if stat.S_ISLNK(st.st_mode):
                print(f"  skipped (a link): {os.path.join(base, name)}")
                continue
            if not (stat.S_ISDIR(st.st_mode) or stat.S_ISREG(st.st_mode)):     # the socket keeps its own group
                continue
            _fix(name, st, gid, dfd)
    _fix(str(top), os.lstat(top), gid)


def _fix(p: str, st: os.stat_result, gid: int, dir_fd: int | None = None) -> None:
    flags = os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK | (os.O_DIRECTORY if stat.S_ISDIR(st.st_mode) else 0)
    try:
        fd = os.open(p, flags, dir_fd=dir_fd)             # NONBLOCK: a file swapped for a pipe never hangs root
    except OSError as e:                                  # gone, or a link now (ELOOP): left alone
        print(f"  skipped ({e.strerror}): {p}")
        return
    try:
        cur = os.fstat(fd)
        if (cur.st_ino, cur.st_dev) != (st.st_ino, st.st_dev):     # changed between the look and the open
            return
        os.fchown(fd, -1, gid)
        mode = stat.S_IMODE(cur.st_mode)
        mode = (mode | stat.S_IRGRP | stat.S_IWGRP) & ~stat.S_IRWXO
        if stat.S_ISDIR(cur.st_mode) or mode & stat.S_IXUSR:
            mode |= stat.S_IXGRP
        if stat.S_ISDIR(cur.st_mode):
            mode |= stat.S_ISGID
        os.fchmod(fd, mode)
    finally:
        os.close(fd)


def remove_old_units(unit_dir: Path) -> list[str]:
    """Step 0: the units of before, if still there — the first install's API (investigatore-api) and V8's MCP server
    (investigatore-mcp, B32: disabled but still a unit of the owner's on port 8002, every address) — each stopped,
    disabled, its file removed, then one daemon-reload. Idempotent: a second run finds nothing and does nothing;
    --dry-run prints the commands and leaves the files. Returns the names removed."""
    gone = []
    for name in OLD_UNITS:
        f = unit_dir / name
        if not (f.exists() or f.is_symlink()):
            continue
        print(f"0. the unit of before {name}: stopped, disabled and removed")
        run("systemctl", "disable", "--now", name, check=False)
        if not DRY:
            f.unlink()
            if name == OLD_UNIT:
                (ROOT / "sys" / "status" / "investigatore.sock").unlink(missing_ok=True)   # the old service's socket
        gone.append(name)
    if gone:
        run("systemctl", "daemon-reload")
        run("systemctl", "reset-failed", *gone, check=False)
    return gone


def install() -> int:
    owner = os.environ.get("SUDO_USER") or ""
    if not DRY and os.geteuid() != 0:
        print("run it with sudo (or --dry-run to see the steps)")
        return 1
    if not owner or owner == "root":
        print("run it with sudo from the owner's account (SUDO_USER names who shares the archive)")
        return 1
    home = Path(pwd.getpwnam(owner).pw_dir)
    remove_old_units(SYSTEMD)
    print("1. groups and the account")
    if not exists("group", API_GROUP):
        run("groupadd", "--system", API_GROUP)
    if not exists("user", USER):
        run("useradd", "--system", "--user-group", "--no-create-home", "--home-dir", "/nonexistent",
            "--shell", "/usr/sbin/nologin", USER)
    for user, group in ((USER, API_GROUP), (owner, GROUP), ("aurora", API_GROUP)):
        if exists("user", user) and not member(user, group):
            run("usermod", "-aG", group, user)
    print("2. no passage through the home: the unit sees only the project (ProtectHome=tmpfs + its binds)")
    run("setfacl", "-x", f"u:{USER}", str(home), check=False)          # given by the first versions of this script
    print("3. the archive's folders (walked without following a link: audit, 10 Nov)")
    for w in WRITABLE:
        d = ROOT / w
        print(f"  {d}: group {GROUP}, group rw, others nothing, folders setgid")
        if not DRY:
            d.mkdir(parents=True, exist_ok=True)
            own(d, grp.getgrnam(GROUP).gr_gid)
    run("chmod", "o+x", str(ROOT / "sys" / "status"))       # the way to the socket; the socket itself is 660
    print(f"4. the unit {UNIT}")
    unit = Path("/etc/systemd/system") / UNIT
    if DRY:
        print(UNIT_TEXT)
    else:
        unit.write_text(UNIT_TEXT, encoding="utf-8")
        os.chmod(unit, 0o644)
    run("systemctl", "daemon-reload")
    run("systemctl", "enable", "--now", UNIT)
    run("systemctl", "restart", UNIT)
    if exists("user", OLD_USER) or exists("group", OLD_API_GROUP) or exists("group", OLD_USER):
        print("5. the first install's account and groups: deleted (the archive already belongs to the new ones)")
        run("setfacl", "-x", f"u:{OLD_USER}", str(home), check=False)
        if exists("user", OLD_USER):
            run("userdel", OLD_USER)
        for g in (OLD_API_GROUP, OLD_USER):
            if exists("group", g):
                run("groupdel", g)
    print("done: «systemctl status evidentia-api»; Aurora reaches the socket after her next restart (new group)")
    return 0


if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] != "install":
        print(__doc__)
        raise SystemExit(2)
    raise SystemExit(install())
